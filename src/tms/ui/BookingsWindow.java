    private void loadBookings(){
        tableModel.setRowCount(0);
        SimpleDateFormat sdf=new SimpleDateFormat("yyyy-MM-dd");
        for (Booking booking : bookingManager.getBookings()) {
            String dateStr=(booking.getBookingDate()!=null)?
                    sdf.format(booking.getBookingDate()):"N/A";
            String userName= (booking.getUser()!=null)?
                    booking.getUser().getName(): "N/A";
            String packageDesc = (booking.getComponent() != null)?
                    booking.getComponent().getDescription() : "N/A";
            
            tableModel.addRow(new Object[]{
                booking.getId(),
                dateStr,
                booking.getStatus(),
                "$"+String.format("%.2f", booking.getTotalPrice()),
                userName,
                packageDesc
                
            });
            
        }
                
    }
